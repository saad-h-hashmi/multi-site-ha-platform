#!/usr/bin/env bash
# Assemble submission/ from the canonical files (docs/, diagrams/, evidence/).
# Regenerate after any documentation change:  make submission
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
S="$ROOT/submission"
rm -rf "$S"; mkdir -p "$S"/{diagrams,evidence}

n=0
cp_doc() { cp "$ROOT/$1" "$S/$2"; n=$((n+1)); }
cp_doc docs/PROJECT_REPORT.md          01_PROJECT_REPORT.md
cp_doc README.md                       02_PROJECT_OVERVIEW.md
cp_doc docs/ARCHITECTURE.md            03_ARCHITECTURE.md
cp_doc docs/NETWORK_DESIGN.md          04_NETWORK_DESIGN.md
cp_doc docs/IP_ADDRESSING_PLAN.md      05_IP_ADDRESSING_PLAN.md
cp_doc docs/HIGH_AVAILABILITY_DESIGN.md 06_HIGH_AVAILABILITY_DESIGN_AND_LIMITATIONS.md
cp_doc docs/TEST_REPORT.md             07_TEST_REPORT.md
cp_doc docs/DEPLOYMENT_GUIDE.md        08_DEPLOYMENT_INSTRUCTIONS.md
cp_doc docs/REBUILD_GUIDE.md           09_REBUILD_BACKUP_RESTORE.md
cp_doc docs/INSTALLATION_GUIDE.md      10_INSTALLATION_GUIDE.md
cp_doc docs/SECURITY.md                11_SECURITY.md
cp_doc FINAL_STATUS.md                 12_FINAL_STATUS.md
cp_doc docs/ARCHITECTURE_DIAGRAM.md    diagrams/ARCHITECTURE_DIAGRAMS.md
cp "$ROOT"/diagrams/*.mmd "$ROOT"/diagrams/*.svg "$S/diagrams/"

# Rewrite links so the package works on its own: diagrams point at the copies in
# submission/diagrams/; other document links point back into the repository's docs/.
for f in "$S"/*.md; do
  sed -i -E 's#\]\((\.\./)?diagrams/#](diagrams/#g; s#\]\((docs/)?([A-Z_]+\.md)#](../docs/\2#g; s#\]\(\.\./docs/(PROJECT_BRIEF|FINAL_STATUS|PROJECT_PROGRESS|README)\.md#](../\1.md#g' "$f"
done
# the diagrams document sits next to its sources: ../diagrams/x -> x
sed -i -E 's#\]\(\.\./diagrams/#](#g; s#\]\(\.\./evidence/#](../evidence/#g' "$S"/diagrams/*.md

# Evidence: every test log (final and earlier failing runs) and all failover runs
cp "$ROOT"/evidence/tests/*.log "$S/evidence/"
cp "$ROOT"/evidence/tests/*.md "$S/evidence/" 2>/dev/null || true
cp -r "$ROOT/evidence/failover" "$S/evidence/failover"

cat > "$S/README.md" <<EOF
# Submission Package: Multi-Site, Fully Automated, Highly Available Platform

**Group:** Saad Hussain Hashmi (70154663) and Sadia Alla Dita (70154570), University of Lahore. Submitted 21 November 2026.

Generated by \`scripts/build-submission.sh\` on $(date '+%Y-%m-%d %H:%M %Z') from the repository's
\`docs/\`, \`diagrams/\` and \`evidence/\` folders. Edit those originals, not these copies.

| File | Content |
|---|---|
| \`01_PROJECT_REPORT.md\` | Final project report (title page complete) |
| \`02_PROJECT_OVERVIEW.md\` | Project overview (repository README) |
| \`03_ARCHITECTURE.md\` | Architecture |
| \`04_NETWORK_DESIGN.md\` | Network design and firewall policy |
| \`05_IP_ADDRESSING_PLAN.md\` | IP addressing plan |
| \`06_HIGH_AVAILABILITY_DESIGN_AND_LIMITATIONS.md\` | HA design and known limitations |
| \`07_TEST_REPORT.md\` | Test report (measured results) |
| \`08_DEPLOYMENT_INSTRUCTIONS.md\` | How to deploy and access |
| \`09_REBUILD_BACKUP_RESTORE.md\` | How to rebuild, back up and restore |
| \`10_INSTALLATION_GUIDE.md\` | Host preparation |
| \`11_SECURITY.md\` | Security controls and accepted weaknesses |
| \`12_FINAL_STATUS.md\` | VERIFIED / FAILED / NOT TESTED / SIMULATED status of every part |
| \`diagrams/\` | Mermaid sources, all diagrams in one document, network topology SVG |
| \`evidence/\` | Genuine logs of the final test runs and all three failover runs |

The sites are simulated on one VM; see \`06_...\` and \`12_FINAL_STATUS.md\`.
EOF
echo "submission/: $n documents, $(ls "$S/diagrams" | wc -l) diagram files, $(find "$S/evidence" -type f | wc -l) evidence files"
